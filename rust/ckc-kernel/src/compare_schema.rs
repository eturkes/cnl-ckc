use crate::k2_manifest::udec_vec;
use crate::k4_bytes::{append, copy, eq};
#[cfg(verus_keep_ghost)]
use ckc_spec::compare as c;
#[cfg(verus_keep_ghost)]
use ckc_spec::v1text::ascii;
#[cfg(verus_keep_ghost)]
use vstd::assert_seqs_equal;
use vstd::prelude::*;
#[cfg(verus_keep_ghost)]
use vstd::string::{StringSliceAdditionalSpecFns, is_ascii_spec_bytes};

verus! {

pub fn ascii_eq(bytes: &Vec<u8>, text: &str) -> (r: bool)
    requires
        text.is_ascii(),
    ensures
        r == (bytes@ == ascii(text@)),
{
    proof {
        is_ascii_spec_bytes(text);
        assert_seqs_equal!(text.spec_bytes() == ascii(text@));
    }
    eq(bytes.as_slice(), text.as_bytes())
}

fn literal(text: &str) -> (r: Vec<u8>)
    requires
        text.is_ascii(),
    ensures
        r@ == ascii(text@),
{
    proof {
        is_ascii_spec_bytes(text);
        assert_seqs_equal!(text.spec_bytes() == ascii(text@));
    }
    copy(text.as_bytes())
}

fn push_literal(out: &mut Vec<u8>, text: &str)
    requires
        text.is_ascii(),
    ensures
        final(out)@ == old(out)@ + ascii(text@),
{
    proof {
        is_ascii_spec_bytes(text);
        assert_seqs_equal!(text.spec_bytes() == ascii(text@));
    }
    append(out, text.as_bytes());
}

fn header() -> (r: Vec<u8>)
    ensures
        r@ == c::schema_header(),
{
    proof {
        reveal_strlit(
            "% schema.pl: the comparison built-ins of the compiled Prolog schema (docs/REFERENCE.md); generated by ckc from the formal specification; do not edit; first-party code, Apache-2.0 WITH LLVM-exception.\n",
        );
    }
    literal(
        "% schema.pl: the comparison built-ins of the compiled Prolog schema (docs/REFERENCE.md); generated by ckc from the formal specification; do not edit; first-party code, Apache-2.0 WITH LLVM-exception.\n",
    )
}

fn rules() -> (r: Vec<u8>)
    ensures
        r@ == c::schema_rules(),
{
    proof {
        reveal_strlit(
            "guideline_satisfies(S, N, B, M) :- atom(S), integer(N), atom(B), integer(M), guideline_within(S, N, B, M).\n",
        );
        reveal_strlit(
            "guideline_satisfies(S, N, U, B, M, V) :- atom(S), integer(N), atom(U), atom(B), integer(M), atom(V), guideline_scale(U, G, R), guideline_scale(V, G, Q), X is N * R, Y is M * Q, guideline_within(S, X, B, Y).\n",
        );
    }
    let mut out = literal(
        "guideline_satisfies(S, N, B, M) :- atom(S), integer(N), atom(B), integer(M), guideline_within(S, N, B, M).\n",
    );
    push_literal(
        &mut out,
        "guideline_satisfies(S, N, U, B, M, V) :- atom(S), integer(N), atom(U), atom(B), integer(M), atom(V), guideline_scale(U, G, R), guideline_scale(V, G, Q), X is N * R, Y is M * Q, guideline_within(S, X, B, Y).\n",
    );
    out
}

fn within_row(i: usize) -> (r: (Vec<u8>, Vec<u8>, Vec<u8>))
    requires
        i < 15,
    ensures
        (r.0@, r.1@, r.2@) == c::within_rows()[i as int],
{
    let (stated, bound, op) = match i {
        0 => ("eq", "geq", ">="),
        1 => ("exactly", "geq", ">="),
        2 => ("geq", "geq", ">="),
        3 => ("greater", "geq", ">="),
        4 => ("eq", "greater", ">"),
        5 => ("exactly", "greater", ">"),
        6 => ("geq", "greater", ">"),
        7 => ("greater", "greater", ">="),
        8 => ("exactly", "leq", "=<"),
        9 => ("leq", "leq", "=<"),
        10 => ("less", "leq", "=<"),
        11 => ("exactly", "less", "<"),
        12 => ("leq", "less", "<"),
        13 => ("less", "less", "=<"),
        _ => ("exactly", "exactly", "=:="),
    };
    proof {
        reveal_strlit("eq");
        reveal_strlit("exactly");
        reveal_strlit("geq");
        reveal_strlit("greater");
        reveal_strlit("leq");
        reveal_strlit("less");
        reveal_strlit(">=");
        reveal_strlit(">");
        reveal_strlit("=<");
        reveal_strlit("<");
        reveal_strlit("=:=");
    }
    (literal(stated), literal(bound), literal(op))
}

fn scale_row(i: usize) -> (r: (Vec<u8>, Vec<u8>, usize))
    requires
        i < 7,
    ensures
        (r.0@, r.1@, r.2 as int) == c::scale_rows()[i as int],
{
    let (unit, group, scale) = match i {
        0 => ("second", "time", 1usize),
        1 => ("minute", "time", 60usize),
        2 => ("hour", "time", 3600usize),
        3 => ("day", "time", 86400usize),
        4 => ("week", "time", 604800usize),
        5 => ("month", "calendar", 1usize),
        _ => ("year", "calendar", 12usize),
    };
    proof {
        reveal_strlit("second");
        reveal_strlit("minute");
        reveal_strlit("hour");
        reveal_strlit("day");
        reveal_strlit("week");
        reveal_strlit("month");
        reveal_strlit("year");
        reveal_strlit("time");
        reveal_strlit("calendar");
    }
    (literal(unit), literal(group), scale)
}

fn push_within(out: &mut Vec<u8>, row: &(Vec<u8>, Vec<u8>, Vec<u8>))
    ensures
        final(out)@ == old(out)@ + c::within_line((row.0@, row.1@, row.2@)),
{
    let ghost before = out@;
    proof {
        reveal_strlit("guideline_within(");
        reveal_strlit(", X, ");
        reveal_strlit(", Y) :- X ");
        reveal_strlit(" Y.\n");
    }
    push_literal(out, "guideline_within(");
    append(out, row.0.as_slice());
    push_literal(out, ", X, ");
    append(out, row.1.as_slice());
    push_literal(out, ", Y) :- X ");
    append(out, row.2.as_slice());
    push_literal(out, " Y.\n");
    proof {
        assert_seqs_equal!(out@ == before + c::within_line((row.0@, row.1@, row.2@)));
    }
}

fn push_scale(out: &mut Vec<u8>, row: &(Vec<u8>, Vec<u8>, usize))
    ensures
        final(out)@ == old(out)@ + c::scale_line((row.0@, row.1@, row.2 as int)),
{
    let ghost before = out@;
    proof {
        reveal_strlit("guideline_scale(");
        reveal_strlit(", ");
        reveal_strlit(").\n");
    }
    push_literal(out, "guideline_scale(");
    append(out, row.0.as_slice());
    push_literal(out, ", ");
    append(out, row.1.as_slice());
    push_literal(out, ", ");
    let number = udec_vec(row.2);
    append(out, number.as_slice());
    push_literal(out, ").\n");
    proof {
        assert_seqs_equal!(out@ == before + c::scale_line((row.0@, row.1@, row.2 as int)));
    }
}

fn within_lines() -> (r: Vec<u8>)
    ensures
        r@ == c::within_lines(c::within_rows()),
{
    let mut out = Vec::new();
    let mut i = 0usize;
    proof {
        assert_seqs_equal!(c::within_rows().skip(0) == c::within_rows());
    }
    while i < 15
        invariant
            i <= 15,
            out@ + c::within_lines(c::within_rows().skip(i as int)) == c::within_lines(
                c::within_rows(),
            ),
        decreases 15 - i,
    {
        let row = within_row(i);
        let ghost before = out@;
        push_within(&mut out, &row);
        proof {
            reveal_with_fuel(c::within_lines, 1);
            assert_seqs_equal!(c::within_rows().skip(i as int).drop_first() == c::within_rows().skip(i as int + 1));
            assert_seqs_equal!(out@ + c::within_lines(c::within_rows().skip(i as int + 1)) == before + c::within_lines(c::within_rows().skip(i as int)));
        }
        i += 1;
    }
    out
}

fn scale_lines() -> (r: Vec<u8>)
    ensures
        r@ == c::scale_lines(c::scale_rows()),
{
    let mut out = Vec::new();
    let mut i = 0usize;
    proof {
        assert_seqs_equal!(c::scale_rows().skip(0) == c::scale_rows());
    }
    while i < 7
        invariant
            i <= 7,
            out@ + c::scale_lines(c::scale_rows().skip(i as int)) == c::scale_lines(
                c::scale_rows(),
            ),
        decreases 7 - i,
    {
        let row = scale_row(i);
        let ghost before = out@;
        push_scale(&mut out, &row);
        proof {
            reveal_with_fuel(c::scale_lines, 1);
            assert_seqs_equal!(c::scale_rows().skip(i as int).drop_first() == c::scale_rows().skip(i as int + 1));
            assert_seqs_equal!(out@ + c::scale_lines(c::scale_rows().skip(i as int + 1)) == before + c::scale_lines(c::scale_rows().skip(i as int)));
        }
        i += 1;
    }
    out
}

pub fn schema_bytes() -> (r: Vec<u8>)
    ensures
        r@ == c::schema_bytes(),
{
    let mut out = header();
    let rules = rules();
    append(&mut out, rules.as_slice());
    let within = within_lines();
    append(&mut out, within.as_slice());
    let scales = scale_lines();
    append(&mut out, scales.as_slice());
    out
}

} // verus!
